#!/usr/bin/env node
/**
 * Regenerates the bundled, versioned emoji dataset from Unicode data files (no runtime CDN).
 *
 * Inputs (download them yourself, pinned versions; both are under the Unicode License v3):
 *   1. emoji-test.txt         https://unicode.org/Public/emoji/<version>/emoji-test.txt
 *   2. CLDR annotations (en)  npm package cldr-annotations-full@<version> → annotations/en/annotations.json
 *
 * Usage:
 *   node scripts/emoji/build-emoji-data.mjs <emoji-test.txt> <annotations.json> <cldr-version>
 *
 * Outputs:
 *   src/Resources/emoji/emoji-data.php  — RGI emoji (fully- and minimally-qualified) => CLDR short name; used by the
 *                                         server-side validator and the Twig rendering helper (aria-label).
 *   src/Resources/public/emoji-data.json — picker dataset (fully-qualified emoji, names, keywords, groups and
 *                                          single skin-tone variants), served as a static bundle asset.
 */
import { readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { dirname, resolve } from 'node:path';

const [, , emojiTestPath, annotationsPath, cldrVersion] = process.argv;
if (!emojiTestPath || !annotationsPath || !cldrVersion) {
  console.error('Usage: node build-emoji-data.mjs <emoji-test.txt> <annotations.json> <cldr-version>');
  process.exit(1);
}

const root = resolve(dirname(fileURLToPath(import.meta.url)), '../..');
const text = readFileSync(emojiTestPath, 'utf8');
const annotations = JSON.parse(readFileSync(annotationsPath, 'utf8')).annotations.annotations;

const versionMatch = text.match(/^# Version: ([0-9.]+)$/m);
if (!versionMatch) throw new Error('emoji-test.txt: no "# Version:" header');
const emojiVersion = versionMatch[1];

const TONES = ['light skin tone', 'medium-light skin tone', 'medium skin tone', 'medium-dark skin tone', 'dark skin tone'];

/** @type {Record<string, string>} */
const valid = {};
/** @type {{char: string, name: string, group: number, version: number}[]} */
const fully = [];
const groups = [];
let group = -1;

for (const line of text.split('\n')) {
  const g = line.match(/^# group: (.+)$/);
  if (g) {
    if (g[1] === 'Component') {
      group = -1;
    } else {
      groups.push(g[1]);
      group = groups.length - 1;
    }
    continue;
  }
  const m = line.match(/^([0-9A-F ]+?)\s*;\s*(fully-qualified|minimally-qualified|unqualified|component)\s*#\s*\S+\s+E([0-9.]+)\s+(.+)$/);
  if (!m) continue;
  const [, cps, status, version, name] = m;
  if (status !== 'fully-qualified' && status !== 'minimally-qualified') continue;
  const char = String.fromCodePoint(...cps.split(' ').map((h) => parseInt(h, 16)));
  valid[char] = name;
  if (status === 'fully-qualified' && group >= 0) fully.push({ char, name, group, version: Number(version) });
}

const byName = new Map(fully.map((e) => [e.name, e]));
/** base name => [5 tone variants] */
const toneVariants = new Map();
const toneChars = new Set();
for (const e of fully) {
  const idx = e.name.lastIndexOf(': ');
  if (idx < 0) continue;
  const toneIdx = TONES.indexOf(e.name.slice(idx + 2));
  if (toneIdx < 0) continue; // multi-tone or other qualifier: validator accepts it, the picker grid does not list it
  const base = e.name.slice(0, idx);
  if (!byName.has(base)) continue;
  if (!toneVariants.has(base)) toneVariants.set(base, ['', '', '', '', '']);
  toneVariants.get(base)[toneIdx] = e.char;
  toneChars.add(e.char);
}
for (const e of fully) {
  if (/: .*skin tone/.test(e.name)) toneChars.add(e.char);
}

const stripVs = (s) => s.replace(/️/g, '');
const entries = [];
for (const e of fully) {
  if (toneChars.has(e.char)) continue;
  const ann = annotations[e.char] ?? annotations[stripVs(e.char)];
  const keywords = (ann?.default ?? []).filter((k) => k !== e.name).join('|');
  const tones = toneVariants.get(e.name);
  // [grapheme, CLDR name, "kw|kw", group index, emoji version (the picker hides versions the browser cannot draw), tones?]
  const row = [e.char, e.name, keywords, e.group, e.version];
  if (tones && tones.every((t) => t !== '')) row.push(tones);
  entries.push(row);
}

const meta = {
  emoji_version: emojiVersion,
  cldr_version: cldrVersion,
  source: 'Unicode emoji-test.txt (UTS #51) + Unicode CLDR annotations (en)',
  license: 'Unicode-3.0',
};

writeFileSync(
  resolve(root, 'src/Resources/public/emoji-data.json'),
  JSON.stringify({ ...meta, groups, emoji: entries }) + '\n',
);

const phpString = (s) => "'" + s.replace(/\\/g, '\\\\').replace(/'/g, "\\'") + "'";
let php = '<?php\n\n';
php += '// Generated by scripts/emoji/build-emoji-data.mjs — do not edit by hand.\n';
php += `// Source: ${meta.source}; Emoji ${emojiVersion}, CLDR ${cldrVersion}; license ${meta.license} (see LICENSE-UNICODE.txt).\n\n`;
php += 'declare(strict_types=1);\n\nreturn [\n';
php += `    'emoji_version' => ${phpString(emojiVersion)},\n`;
php += `    'cldr_version' => ${phpString(cldrVersion)},\n`;
php += "    'emoji' => [\n";
for (const [char, name] of Object.entries(valid)) {
  php += `        ${phpString(char)} => ${phpString(name)},\n`;
}
php += '    ],\n];\n';
writeFileSync(resolve(root, 'src/Resources/emoji/emoji-data.php'), php);

console.log(`Emoji ${emojiVersion} / CLDR ${cldrVersion}: ${Object.keys(valid).length} valid sequences, ${entries.length} picker entries, ${groups.length} groups`);
